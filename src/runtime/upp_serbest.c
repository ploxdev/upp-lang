/* =====================================================================
 * Gerçek zamanlı saat (CMOS), güç, ekran, işlemci adı
 * ===================================================================== */
static uint8_t _upp_cmos(uint8_t r) {
    _upp_outb(0x70, r);
    return _upp_inb(0x71);
}

static int _upp_bcd(int v) {
    return (v & 0x0F) + (v >> 4) * 10;
}

static void _upp_mk_iki(char** s, int v) {
    char b[2];
    b[0] = (char)('0' + (v / 10) % 10);
    b[1] = (char)('0' + v % 10);
    _upp_m_ekle_n(s, b, 2u, 1);
}

/* "YYYY-AA-GG SS:DD:ss" (CMOS saati; QEMU'da UTC) */
static char* upp_cekirdek_tarih(void) {
    int i, sn, dk, sa, gun, ay, yil, b;
    char* s;
    for (i = 0; i < 100000 && (_upp_cmos(0x0A) & 0x80); i++) {
    }
    sn = _upp_cmos(0x00);
    dk = _upp_cmos(0x02);
    sa = _upp_cmos(0x04);
    gun = _upp_cmos(0x07);
    ay = _upp_cmos(0x08);
    yil = _upp_cmos(0x09);
    b = _upp_cmos(0x0B);
    if (!(b & 4)) {
        int pm = sa & 0x80;
        sn = _upp_bcd(sn);
        dk = _upp_bcd(dk);
        sa = _upp_bcd(sa & 0x7F) | pm;
        gun = _upp_bcd(gun);
        ay = _upp_bcd(ay);
        yil = _upp_bcd(yil);
    }
    if (!(b & 2) && (sa & 0x80)) {
        sa = ((sa & 0x7F) + 12) % 24;
    }
    sa &= 0x7F;
    s = upp_mk_bas();
    upp_mk_sayi(&s, 2000 + yil);
    _upp_m_ekle_n(&s, "-", 1u, 1);
    _upp_mk_iki(&s, ay);
    _upp_m_ekle_n(&s, "-", 1u, 1);
    _upp_mk_iki(&s, gun);
    _upp_m_ekle_n(&s, " ", 1u, 1);
    _upp_mk_iki(&s, sa);
    _upp_m_ekle_n(&s, ":", 1u, 1);
    _upp_mk_iki(&s, dk);
    _upp_m_ekle_n(&s, ":", 1u, 1);
    _upp_mk_iki(&s, sn);
    return s;
}

